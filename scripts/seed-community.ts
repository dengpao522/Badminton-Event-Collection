async function main() {
  // ---------- 1) 官方账号（幂等：按 email） ----------
  let official = await prisma.user.findUnique({ where: { email: OFFICIAL.email } });
  if (!official) {
    // 随机密码仅写入库不落日志：该账号只由服务端脚本使用，不接受外部登录
    const rndPassword = randomBytes(24).toString('hex');
    official = await prisma.user.create({
      data: {
        email: OFFICIAL.email,
        passwordHash: hashPassword(rndPassword),
        name: OFFICIAL.name,
        bio: OFFICIAL.bio,
      },
    });
    console.log('[官号] 已创建：全羽小助手');
  } else {
    console.log('[官号] 已存在，跳过创建');
  }

  // ---------- 2) 种子帖子（幂等：作者 + 标题） ----------
  let inserted = 0;
  let skipped = 0;
  for (const p of POSTS) {
    const existing = await prisma.post.findFirst({
      where: { userId: official.id, title: p.title },
    });
    if (existing) {
      skipped++;
      continue;
    }
    // 关联赛事：按名称精确匹配（找不到不关联，不阻断冷启动）
    let eventId: string | null = null;
    if (p.eventName) {
      const ev = await prisma.event.findFirst({ where: { name: p.eventName }, select: { id: true } });
      eventId = ev?.id ?? null;
    }
    await prisma.post.create({
      data: {
        userId: official.id,
        title: p.title,
        content: p.content,
        images: '[]',
        topic: p.topic,
        eventId,
      },
    });
    inserted++;
  }
  console.log(`[种子内容] 新增 ${inserted}，跳过 ${skipped}，共 ${POSTS.length} 条`);

  const total = await prisma.post.count();
  console.log(`社区帖子总数：${total}`);
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error('冷启动导入失败:', e);
    await prisma.$disconnect();
    process.exit(1);
  });
